"""
List the SSL/TLS certificates that Caddy generates for the domain names of the platform.

The Caddy container converts its Caddyfile to JSON, and it prints the certificates that
it stores, but never their private keys. On the host, we find out which domain names
Caddy manages, with a simplified version of the Caddy automatic HTTPS logic, and we
match them with the stored certificates.
"""

from __future__ import annotations

import ipaddress
import json
import re
import typing as t
from dataclasses import dataclass
from datetime import datetime, timezone
from urllib.parse import urlsplit

from Crypto.IO import PEM
from Crypto.Util.asn1 import DerObject, DerSequence

from tutor import exceptions, fmt, utils
from tutor.types import Config, get_typed

COMMAND_SHORT_HELP = "List the SSL/TLS certificates generated by Caddy"
COMMAND_HELP = (
    "List the SSL/TLS certificates that Caddy generates for the domain names of the "
    "platform, when ENABLE_HTTPS is true. For each domain name, print the expiration "
    "and renewal dates of its certificate, or whether Caddy has yet to request one."
)
DOCS_URL = "https://docs.tutor.edly.io/troubleshooting.html#letsencrypt-rate-limits"

SEPARATOR = "@@TUTOR-CADDY@@"
CADDYFILE_PATH = "/etc/caddy/Caddyfile"
CERTIFICATES_DIR = "/data/caddy/certificates"
RUNNING_CONFIG_PATH = "/config/caddy/autosave.json"
HTTP_PORT = 80
MAX_TIME = datetime.max.replace(tzinfo=timezone.utc)

# Issuers are identified by the directory where Caddy stores their certificates
LETSENCRYPT_CA = "https://acme-v02.api.letsencrypt.org/directory"
LETSENCRYPT = "acme-v02.api.letsencrypt.org-directory"
LETSENCRYPT_STAGING = "acme-staging-v02.api.letsencrypt.org-directory"
INTERNAL = "local"
ISSUER_NAMES = {
    LETSENCRYPT: "Let's Encrypt",
    LETSENCRYPT_STAGING: "Let's Encrypt (staging)",
    "acme.zerossl.com-v2-dv90": "ZeroSSL",
    INTERNAL: "Caddy internal",
}

STATUS_VALID = "valid"
STATUS_RENEWAL_DUE = "renewal due"
STATUS_EXPIRED = "expired"
STATUS_MISSING = "missing (will be requested)"
STATUS_NOT_CONFIGURED = "not configured"
STATUS_NOT_USED = "not used"
STATUS_UNREADABLE = "unreadable"
STATUSES_IN_USE = (STATUS_VALID, STATUS_RENEWAL_DUE, STATUS_EXPIRED)


def script(
    certificates_dir: str = CERTIFICATES_DIR,
    running_config_path: str = RUNNING_CONFIG_PATH,
) -> str:
    """
    Shell script that runs in the Caddy container. It prints the environment variable
    of the default site port, the Caddyfile converted to JSON, the JSON configuration
    that Caddy runs, and the stored certificates with their metadata. Private keys
    (*.key files) are never read.
    """
    return f"""set -u
sep={SEPARATOR}
err=/tmp/tutor-caddy-$$.err
echo "$sep default-site-port ${{default_site_port:-}}"
echo "$sep adapted"
caddy adapt --config {CADDYFILE_PATH} --adapter caddyfile 2> "$err"
status=$?
echo
echo "$sep adapt-status $status"
cat "$err"
echo
rm -f "$err"
echo "$sep running"
cat "{running_config_path}" 2> /dev/null
echo
for crt in "{certificates_dir}"/*/*/*.crt; do
    [ -f "$crt" ] || continue
    echo "$sep crt $crt"
    cat "$crt"
    echo
    echo "$sep json"
    cat "${{crt%.crt}}.json" 2> /dev/null
    echo
done
echo "$sep end"
"""


@dataclass(frozen=True)
class Section:
    kind: str
    argument: str
    body: str


@dataclass(frozen=True)
class StoredCertificate:
    issuer: str
    name_dir: str
    names: tuple[str, ...]
    # (not before, not after), or None if the certificate cannot be parsed
    validity: t.Optional[tuple[datetime, datetime]]
    # Renewal time selected with ACME Renewal Information (ARI)
    ari_time: t.Optional[datetime]


@dataclass(frozen=True)
class ContainerOutput:
    default_site_port: str
    adapted: dict[str, t.Any]
    running: t.Optional[dict[str, t.Any]]
    stored: list[StoredCertificate]


def split_sections(output: str) -> list[Section]:
    parts = re.split(
        f"^{re.escape(SEPARATOR)} (.*)$", output.replace("\r\n", "\n"), flags=re.M
    )
    sections = []
    for header, body in zip(parts[1::2], parts[2::2]):
        kind, _, argument = header.partition(" ")
        sections.append(Section(kind, argument.strip(), body.strip("\n")))
    return sections


def parse_output(output: str) -> ContainerOutput:
    """
    Parse the output of the script that runs in the Caddy container.
    """
    sections = split_sections(output)

    def section(kind: str) -> Section:
        return next((s for s in sections if s.kind == kind), Section(kind, "", ""))

    if not any(s.kind == "end" for s in sections):
        raise exceptions.TutorError("The output of the Caddy container is incomplete.")
    if section("adapt-status").argument != "0":
        raise exceptions.TutorError(
            f"Caddy could not parse its Caddyfile:\n{section('adapt-status').body}"
        )
    adapted = _load_json_object(section("adapted").body)
    if adapted is None:
        raise exceptions.TutorError("Unexpected output from `caddy adapt`.")
    stored = [
        parse_stored_certificate(crt.argument, crt.body, metadata.body)
        for crt, metadata in zip(sections, sections[1:])
        if crt.kind == "crt" and metadata.kind == "json"
    ]
    running = _load_json_object(section("running").body)
    return ContainerOutput(
        section("default-site-port").argument, adapted, running, stored
    )


def _load_json_object(text: str) -> t.Optional[dict[str, t.Any]]:
    try:
        value = json.loads(text)
    except ValueError:
        return None
    return value if isinstance(value, dict) else None


def _get(data: t.Any, *keys: str) -> t.Any:
    """
    Get a value from nested JSON objects, or None if it is missing.
    """
    for key in keys:
        data = data.get(key) if isinstance(data, dict) else None
    return data


def parse_stored_certificate(path: str, crt: str, metadata: str) -> StoredCertificate:
    """
    Caddy stores certificates in <issuer>/<name>/<name>.crt, where <name> is the
    storage key of the domain name, and their metadata in <name>.json.
    """
    parts = path.split("/")
    if len(parts) < 3:
        raise exceptions.TutorError(f"Unexpected certificate path: {path}")
    issuer, name_dir = parts[-3:-1]
    try:
        validity: t.Optional[tuple[datetime, datetime]] = parse_validity(crt)
    except (ValueError, IndexError, TypeError):
        validity = None
    data = _load_json_object(metadata)
    sans = _get(data, "sans")
    names = (
        tuple(n for n in sans if isinstance(n, str)) if isinstance(sans, list) else ()
    )
    # "_selectedTime" is an internal field of acmez, the ACME library of Caddy: if it
    # goes missing, renewal times are estimated.
    ari_time = _get(data, "issuer_data", "renewal_info", "_selectedTime")
    return StoredCertificate(
        issuer, name_dir, names or (name_dir,), validity, parse_go_time(ari_time)
    )


def parse_validity(pem: str) -> tuple[datetime, datetime]:
    """
    Return the validity period of the first certificate of a PEM bundle, which is the
    leaf certificate in the files that Caddy stores.
    """
    end = "-----END CERTIFICATE-----"
    der, _marker, _encrypted = PEM.decode(pem[: pem.index(end) + len(end)])
    tbs = _der_sequence(_der_sequence(der)[0])
    # Fields: [0] version (absent from v1 certificates), serial number, signature
    # algorithm, issuer, validity, ...
    validity = tbs[4] if isinstance(tbs[0], bytes) and tbs[0][:1] == b"\xa0" else tbs[3]
    not_before, not_after = [_parse_asn1_time(v) for v in _der_sequence(validity)]
    return not_before, not_after


def _der_sequence(der: bytes) -> list[t.Any]:
    """
    Elements of a DER sequence: INTEGER elements are decoded to int, and the others
    are returned as DER-encoded bytes.
    """
    sequence = DerSequence().decode(der)
    return [sequence[i] for i in range(len(sequence))]


def _parse_asn1_time(der: bytes) -> datetime:
    text = DerObject().decode(der).payload.decode("ascii")
    if der[0] == 0x17:  # UTCTime, with a 2-digit year (RFC 5280)
        text = ("19" if int(text[:2]) >= 50 else "20") + text
    elif der[0] != 0x18:  # GeneralizedTime
        raise ValueError(f"Unexpected ASN.1 time tag: {der[0]:#x}")
    return datetime.strptime(text, "%Y%m%d%H%M%SZ").replace(tzinfo=timezone.utc)


def parse_go_time(value: t.Any) -> t.Optional[datetime]:
    """
    Parse a timestamp written by Go. Python 3.10 cannot parse its nanoseconds or its
    "Z" suffix with datetime.fromisoformat. Fractions of seconds are ignored.
    """
    match = re.fullmatch(r"([\d-]+T[\d:]+)(?:\.\d+)?(Z|[+-][\d:]+)", str(value))
    if not match:
        return None
    try:
        parsed = datetime.fromisoformat(match[1] + match[2].replace("Z", "+00:00"))
    except ValueError:
        return None
    return parsed.astimezone(timezone.utc)


def storage_key(name: str) -> str:
    """
    Name of the directory where Caddy stores a certificate, or the certificates of an
    issuer. Port of certmagic.KeyBuilder.Safe.
    """
    key = name.strip().lower().replace(" ", "_").replace("+", "_plus_")
    key = key.replace("*", "wildcard_").replace(":", "-").replace("..", "")
    return re.sub(r"[^\w@.-]", "", key, flags=re.ASCII)


def issuer_key(issuer: dict[str, t.Any]) -> str:
    """
    Storage key of a certificate issuer of the Caddy configuration.
    """
    module = issuer.get("module") or ""
    if module == "internal":
        return storage_key(issuer.get("ca") or INTERNAL)
    if module != "acme":
        return storage_key(module)
    url = urlsplit(issuer.get("ca") or LETSENCRYPT_CA)
    path = url.path.replace("/", "-").replace("\\", "-").strip("-")
    return storage_key(f"{url.netloc}-{path}" if path else url.netloc)


def is_internal(name: str) -> bool:
    """
    Public CAs, such as Let's Encrypt, do not issue certificates for these domain
    names and IP addresses: Caddy issues them a certificate from its internal CA.
    """
    suffixes = (".localhost", ".local", ".internal", ".home.arpa")
    if name == "localhost" or name.endswith(suffixes):
        return True
    ip = _ip_address(name)
    return ip is not None and (ip.is_private or ip.is_loopback or ip.is_link_local)


def _ip_address(name: str) -> t.Optional[ipaddress.IPv4Address | ipaddress.IPv6Address]:
    try:
        return ipaddress.ip_address(name)
    except ValueError:
        return None


@dataclass(frozen=True)
class Domain:
    name: str
    issuers: tuple[str, ...]  # Storage keys of the issuers, by order of preference
    internal: bool


def managed_domains(adapted: dict[str, t.Any]) -> list[Domain]:
    """
    Domain names that Caddy obtains certificates for, from its JSON configuration.
    This is a simplified port of the Caddy automatic HTTPS logic.
    """
    http_port = str(_get(adapted, "apps", "http", "http_port") or HTTP_PORT)
    policies = _get(adapted, "apps", "tls", "automation", "policies") or []
    names = set()
    for server in (_get(adapted, "apps", "http", "servers") or {}).values():
        automatic_https = server.get("automatic_https") or {}
        listen = server.get("listen") or []
        if (
            automatic_https.get("disable")
            or automatic_https.get("disable_certificates")
            or (listen and all(a.rsplit(":", 1)[-1] == http_port for a in listen))
        ):
            continue
        skip = [
            s.lower()
            for key in ("skip", "skip_certificates")
            for s in automatic_https.get(key) or []
        ]
        for route in server.get("routes") or []:
            for matcher in route.get("match") or []:
                for name in [host.lower() for host in matcher.get("host") or []]:
                    # Placeholders, such as {http.request.host}, are ignored
                    valid = re.fullmatch(r"(\*\.)?[\w:-]+(\.[\w:-]+)*", name)
                    if valid and name not in skip:
                        names.add(name)
    return [_domain(name, policies) for name in sorted(names)]


def _domain(name: str, policies: list[dict[str, t.Any]]) -> Domain:
    """
    The automation policy of a domain name is the first one that lists it in its
    subjects, or that has no subjects. Wildcard subjects are not supported. Caddy
    issues certificates for internal names from its internal CA, unless their policy
    lists them in its subjects with issuers of its own (e.g. "tls { issuer acme }"),
    and for all IP addresses when there are no policies.
    """
    policy = next((p for p in policies if name in (p.get("subjects") or [name])), {})
    explicit = name in (policy.get("subjects") or []) and policy.get("issuers")
    if not explicit and (is_internal(name) or (not policies and _ip_address(name))):
        return Domain(name, (INTERNAL,), True)
    issuers = policy.get("issuers") or [{"module": "acme"}]
    return Domain(
        name,
        tuple(issuer_key(issuer) for issuer in issuers),
        all(issuer.get("module") == "internal" for issuer in issuers),
    )


@dataclass(frozen=True)
class Row:
    domain: str
    status: str
    issuer: str
    certificate: t.Optional[StoredCertificate] = None


@dataclass(frozen=True)
class Report:
    rows: list[Row]
    stored_count: int
    in_use_count: int
    new: list[Domain]  # Domain names that Caddy will request a certificate for


def utcnow() -> datetime:
    return datetime.now(timezone.utc)


def renewal_time(
    validity: tuple[datetime, datetime], ari_time: t.Optional[datetime]
) -> tuple[datetime, bool]:
    """
    Return the time when Caddy renews a certificate, and whether it is estimated.

    Caddy renews certificates when a third of their lifetime remains, or earlier, at
    the time selected with ACME Renewal Information (ARI): see certNeedsRenewal in
    certmagic/certificates.go. An ARI time outside of the validity period belongs to
    the previous certificate.
    """
    not_before, not_after = validity
    ratio_time = not_after - (not_after - not_before) / 3
    if ari_time and not_before <= ari_time <= not_after:
        return min(ari_time, ratio_time), False
    return ratio_time, True


def certificate_status(certificate: StoredCertificate, now: datetime) -> str:
    if certificate.validity is None:
        return STATUS_UNREADABLE
    if now >= certificate.validity[1]:
        return STATUS_EXPIRED
    if now >= renewal_time(certificate.validity, certificate.ari_time)[0]:
        return STATUS_RENEWAL_DUE
    return STATUS_VALID


def build_report(
    domains: list[Domain], stored: list[StoredCertificate], now: datetime
) -> Report:
    """
    For each one of its issuers, Caddy loads the certificate of a domain name from
    <issuer>/<storage key>, and it uses the most recent one. When a candidate cannot be
    read, we cannot tell which one is the most recent, so it is the one we report.
    """
    rows = []
    used = []
    new = []
    for domain in domains:
        key = storage_key(domain.name)
        candidates = [
            c for c in stored if c.name_dir == key and c.issuer in domain.issuers
        ]
        if not candidates:
            rows.append(Row(domain.name, STATUS_MISSING, domain.issuers[0]))
            if not domain.internal:
                new.append(domain)
            continue
        certificate = max(
            candidates, key=lambda c: c.validity[0] if c.validity else MAX_TIME
        )
        used.append(certificate)
        status = certificate_status(certificate, now)
        rows.append(Row(domain.name, status, certificate.issuer, certificate))

    configured_keys = {storage_key(domain.name) for domain in domains}
    for certificate in stored:
        if certificate in used:
            continue
        status = STATUS_NOT_CONFIGURED
        if certificate.validity is None:
            status = STATUS_UNREADABLE
        elif certificate.name_dir in configured_keys:
            status = STATUS_NOT_USED
        domain_names = ", ".join(certificate.names)
        rows.append(Row(domain_names, status, certificate.issuer, certificate))
    rows = sorted(rows, key=lambda row: row.domain)
    return Report(rows, len(stored), len(used), new)


def format_report(report: Report, now: datetime, logs_command: str) -> str:
    table: list[tuple[str, ...]] = [
        ("DOMAIN", "STATUS", "ISSUER", "EXPIRES (UTC)", "RENEWAL (UTC)")
    ]
    estimated_renewals = False
    for row in report.rows:
        expires = renewal = "-"
        certificate = row.certificate
        if certificate and certificate.validity:
            not_after = certificate.validity[1]
            expires = f"{not_after:%Y-%m-%d %H:%M} ({_relative_time(not_after, now)})"
            if row.status in STATUSES_IN_USE:
                time, estimated = renewal_time(
                    certificate.validity, certificate.ari_time
                )
                renewal = f"{'~' if estimated else ''}{time:%Y-%m-%d %H:%M}"
                estimated_renewals |= estimated
        issuer = ISSUER_NAMES.get(row.issuer, row.issuer)
        table.append((row.domain, row.status, issuer, expires, renewal))

    in_use = report.in_use_count
    summary = f"Certificates stored by Caddy: {report.stored_count}"
    if in_use != report.stored_count:
        summary += f", of which {in_use} {'is' if in_use == 1 else 'are'} in use"
    renewals = [
        row for row in report.rows if row.status in (STATUS_RENEWAL_DUE, STATUS_EXPIRED)
    ]
    summary += f".\nRenewals due: {len(renewals)}."
    if any(row.issuer in (LETSENCRYPT, LETSENCRYPT_STAGING) for row in renewals):
        summary += (
            " Caddy renews certificates automatically, and Let's Encrypt exempts renewals"
            " that are coordinated with ARI (ACME Renewal Information) from its rate limits."
        )
    summary += f"\nNew certificates that Caddy will request: {len(report.new)}."
    if report.new:
        summary += (
            f"\nIf they remain missing, check the Caddy logs with `{logs_command}`."
        )
    if any(LETSENCRYPT in domain.issuers for domain in report.new):
        summary += (
            "\nLet's Encrypt issues at most 50 new certificates per registered domain,"
            f" and 5 certificates for the same domain names, every 7 days. See: {DOCS_URL}"
        )
    if estimated_renewals:
        summary += (
            "\n~: estimated renewal date, as the certificate authority provided no"
            " renewal information (ARI)."
        )
    return f"{utils.format_table(table)}\n\n{summary}"


def _relative_time(when: datetime, now: datetime) -> str:
    seconds = abs((when - now).total_seconds())
    if seconds >= 86400:
        count, unit = int(seconds // 86400), "day"
    elif seconds >= 3600:
        count, unit = int(seconds // 3600), "hour"
    else:
        count, unit = int(seconds // 60), "minute"
    text = f"{count} {unit}{'' if count == 1 else 's'}"
    if seconds < 60:
        text = "less than a minute"
    return f"in {text}" if when >= now else f"{text} ago"


def print_certificates(
    config: Config,
    run_script: t.Callable[[str], bytes],
    start_command: str,
    restart_command: str,
    logs_command: str,
) -> None:
    """
    Print the certificates of Caddy, and alerts about them.

    Arguments:
        run_script: runs a shell script in the Caddy container and returns its output.
        start_command: the command that starts Caddy.
        restart_command: the command that restarts Caddy with the latest configuration.
        logs_command: the command that prints the logs of Caddy.
    """
    if not get_typed(config, "ENABLE_HTTPS", bool, False):
        fmt.echo_info(
            "Caddy does not generate SSL/TLS certificates, because ENABLE_HTTPS is false."
        )
        return
    if not get_typed(config, "ENABLE_WEB_PROXY", bool, True):
        fmt.echo_info(
            "Caddy does not generate SSL/TLS certificates, because ENABLE_WEB_PROXY is"
            " false: they are managed by the web proxy that runs in front of Caddy."
        )
        return
    try:
        raw_output = run_script(script())
    except exceptions.TutorError as e:
        raise exceptions.TutorError(
            "Could not read the certificates from the Caddy container. Is it running?"
            f" Start it with `{start_command}`."
        ) from e
    try:
        output = parse_output(raw_output.decode("utf-8", "replace"))
    except exceptions.TutorError as e:
        # For instance, the environment was deleted and generated again, and the
        # Caddyfile that is mounted in the container no longer exists
        raise exceptions.TutorError(
            f"{e}\nIf you changed the Caddyfile, restart Caddy with `{restart_command}`."
        ) from e
    if output.default_site_port:
        fmt.echo_alert(
            f"Caddy was started before HTTPS was enabled: restart it with `{restart_command}`."
        )
        return
    storage_module = _get(output.adapted, "storage", "module")
    if storage_module:
        fmt.echo_info(
            f'Caddy stores its certificates with the "{storage_module}" storage module:'
            " this command only supports the default storage."
        )
        return
    servers = (_get(output.adapted, "apps", "http", "servers") or {}).values()
    if servers and all(_get(s, "automatic_https", "disable") for s in servers):
        fmt.echo_info(
            'Caddy does not generate SSL/TLS certificates: automatic HTTPS is disabled ("auto_https off").'
        )
        return
    now = utcnow()
    report = build_report(managed_domains(output.adapted), output.stored, now)
    if not report.rows:
        fmt.echo_info(
            "Caddy does not obtain SSL/TLS certificates automatically for any domain name."
        )
        return

    fmt.echo(format_report(report, now, logs_command))
    if output.running is not None and output.running != output.adapted:
        fmt.echo_alert(
            f"Caddy runs an older configuration than its Caddyfile: restart it with `{restart_command}`."
        )
    expired = [row.domain for row in report.rows if row.status == STATUS_EXPIRED]
    if expired:
        fmt.echo_alert(
            f"Some certificates have expired, which means that Caddy could not renew them: {', '.join(expired)}."
            f" Check the Caddy logs with `{logs_command}`."
        )
